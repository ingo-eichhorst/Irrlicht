#!/usr/bin/env bash
# Drive one Claude Code Desktop Local cell through the safe Go driver.
#
# Two input shapes, the same two run-cell.sh passes every other adapter: a bare
# PROMPT string (one no-tool turn), or a recipe SCRIPT — a JSON array of step
# objects in the shared recipe grammar. The Go driver owns the grammar; this
# file only routes the input to the right flag.

set -euo pipefail

if [[ $# -ne 5 ]]; then
  echo "usage: driver-desktop.sh <staging> <preferred-uuid> <timeout-s> <settings-path> <prompt-or-script>" >&2
  exit 2
fi

# recipe-lint contract (#508 #4, extended for the Desktop profile by #1888): the
# step types this driver genuinely ELICITS, and — for the Desktop profile only —
# the control that is MISSING for each step type it cannot.
#
# THE GRAMMAR'S ONE OWNER IS THE GO DRIVER, not this file. Every other adapter's
# driver IS the shell script, so DRIVE_ELICITS there is the source. Here the
# driver is tools/onboarding-factory/cmd/desktop-driver, and these two lines are
# the scraped declaration recipe-lint and desktop-profile.sh read. They are
# generated by `desktop-driver primitives` and pinned by
# desktopdriver's TestDriverDesktopDeclarationMatchesTheGoGrammar, which fails
# when they drift from the Go tables — so they cannot rot silently.
#
# Regenerate with:
#   go run ./tools/onboarding-factory/cmd/desktop-driver primitives
#
# shellcheck disable=SC2034  # scraped from this file's SOURCE by tools/onboarding-factory/scripts/lib/recipe-lint.sh (sed), never expanded in shell
DRIVE_ELICITS="archive interrupt keys mode model send sleep start_session wait_turn"
# shellcheck disable=SC2034  # scraped from this file's SOURCE by tools/onboarding-factory/scripts/lib/desktop-profile.sh (sed), never expanded in shell
DRIVE_MISSING_CONTROLS="exit_clean:session-exit reset_session:session-reset restart:session-restart resume:session-resume session:session-list-row sigkill:agent-process-kill slash:slash-command-entry"
# The Desktop composer stores a typed "/command" as prompt text; nothing
# measured shows it executing one. A recipe must therefore not smuggle a slash
# command through a `send` step — recipe-lint refuses that shape on this value.
# shellcheck disable=SC2034  # scraped from this file's SOURCE by tools/onboarding-factory/scripts/lib/recipe-lint.sh (sed), never expanded in shell
DRIVE_SLASH_REQUIRES_STEP_TYPE=true

STAGING="$1"
TIMEOUT_S="$3"
DRIVER_INPUT="$5"
DRIVER_LOG="$STAGING/driver.log"
PROMPT_FILE="$STAGING/desktop-prompt.txt"
SCRIPT_FILE="$STAGING/desktop-script.json"
trap 'rm -f "$PROMPT_FILE" "$SCRIPT_FILE"' EXIT

: "${IRRLICHT_REPO_ROOT:?IRRLICHT_REPO_ROOT is required}"
: "${IRRLICHT_DESKTOP_DRIVER_BIN:?IRRLICHT_DESKTOP_DRIVER_BIN is required}"
: "${IRRLICHT_DESKTOP_HELPER_BIN:?IRRLICHT_DESKTOP_HELPER_BIN is required}"
: "${IRRLICHT_BIND_ADDR:?IRRLICHT_BIND_ADDR is required}"
: "${IRRLICHT_DAEMON_VERSION:?IRRLICHT_DAEMON_VERSION is required}"

command -v jq >/dev/null || { echo "driver-desktop.sh: jq is required" >&2; exit 2; }

# A recipe cell arrives as a JSON array of steps; a prompt cell as plain text.
# Deciding on the PARSE rather than on a leading "[" keeps a prompt that happens
# to start with a bracket out of the script path.
INPUT_FLAG=(--prompt-file "$PROMPT_FILE")
if jq -e 'type == "array"' >/dev/null 2>&1 <<<"$DRIVER_INPUT"; then
  printf '%s' "$DRIVER_INPUT" > "$SCRIPT_FILE"
  INPUT_FLAG=(--script-file "$SCRIPT_FILE")
else
  printf '%s' "$DRIVER_INPUT" > "$PROMPT_FILE"
fi
mkdir -p "$STAGING/cwd"

set +e
"$IRRLICHT_DESKTOP_DRIVER_BIN" \
  --repo-root "$IRRLICHT_REPO_ROOT" \
  --staging "$STAGING" \
  --workspace "$STAGING/cwd" \
  "${INPUT_FLAG[@]}" \
  --helper "$IRRLICHT_DESKTOP_HELPER_BIN" \
  --daemon-address "$IRRLICHT_BIND_ADDR" \
  --recordings "$STAGING/recordings" \
  --irrlicht-version "$IRRLICHT_DAEMON_VERSION" \
  --timeout "${TIMEOUT_S}s" \
  >"$DRIVER_LOG.stdout" 2>"$DRIVER_LOG.stderr"
EXIT_CODE=$?
set -e

{
  echo "=== stdout ==="
  cat "$DRIVER_LOG.stdout"
  echo
  echo "=== stderr ==="
  cat "$DRIVER_LOG.stderr"
  echo
  echo "=== exit code: $EXIT_CODE ==="
} > "$DRIVER_LOG"

case "$EXIT_CODE" in
  0) EXIT_REASON="ok" ;;
  # The Go driver reserves 6 for `not runnable through Desktop`: a recipe that
  # needs a control this driver cannot elicit. It is a REFUSAL, not a failed
  # run — nothing about Claude Desktop was changed — so it gets its own reason
  # rather than being graded as a driver fault.
  6) EXIT_REASON="not_runnable_through_desktop" ;;
  *) EXIT_REASON="nonzero($EXIT_CODE)" ;;
esac
printf '%s\n' "$EXIT_REASON" > "$STAGING/driver.exit-reason"
echo "drive-claudecode-desktop: $EXIT_REASON (log=$DRIVER_LOG)"
exit "$EXIT_CODE"
